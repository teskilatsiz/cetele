function normalizeLanguage(languageCode?: string | null): AppLanguage {
  const lower = (languageCode || DEFAULT_LANGUAGE).toLowerCase();
  const base = lower.split('-')[0] as AppLanguage;
  return SUPPORTED_LANGUAGES.includes(base) ? base : DEFAULT_LANGUAGE;
}

function readDeviceLanguage(): AppLanguage {
  try {
    return normalizeLanguage(getLocales()[0]?.languageCode ?? getLocales()[0]?.languageTag);
  } catch {
    if (Platform.OS === 'web' && typeof navigator !== 'undefined') {
      return normalizeLanguage(navigator.language);
    }
    return DEFAULT_LANGUAGE;
  }
}

let currentLanguage = readDeviceLanguage();

export function getCurrentLanguage() {
  return currentLanguage;
}

export function translate(key: TranslationKey, params?: Record<string, string | number>) {
  const template = translations[currentLanguage]?.[key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;
  if (!params) return template;
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replace(new RegExp(`{{\\s*${name}\\s*}}`, 'g'), String(value)),
    template
  );
}

export const t = translate;

export const LANGUAGE_STORAGE_KEY = 'cetele_app_language';

interface I18nContextValue {
  language: AppLanguage;
  t: typeof translate;
  setLanguage: (lang: AppLanguage) => Promise<void>;
}

const I18nContext = createContext<I18nContextValue>({
  language: currentLanguage,
  t: translate,
  setLanguage: async () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(currentLanguage);

  useEffect(() => {
    let active = true;
    const syncLanguage = async () => {
      try {
        const stored = await AsyncStorage.getItem(LANGUAGE_STORAGE_KEY);
        if (!active) return;
        if (stored && SUPPORTED_LANGUAGES.includes(stored as AppLanguage)) {
          currentLanguage = stored as AppLanguage;
          setLanguageState(stored as AppLanguage);
        } else {
          const nextLanguage = readDeviceLanguage();
          currentLanguage = nextLanguage;
          setLanguageState(nextLanguage);
        }
      } catch (error) {
        console.error('Error reading language from storage', error);
      }
    };

    syncLanguage();

    const subscription = Platform.OS === 'android'
      ? AppState.addEventListener('change', (state) => {
          if (state === 'active') void syncLanguage();
        })
      : null;

    return () => {
      active = false;
      subscription?.remove();
    };
  }, []);

  const setLanguage = useCallback(async (lang: AppLanguage) => {
    try {
      await AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
      currentLanguage = lang;
      setLanguageState(lang);
    } catch (error) {
      console.error('Error saving language', error);
    }
  }, []);

  const value = useMemo(() => ({ language, t: translate, setLanguage }), [language, setLanguage]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
